"""Render Dokploy's flat service map without resolving environment variables.

Developer tool: requires PyYAML (tested with 6.0.3). No Docker or secrets needed.
"""
import argparse
from copy import deepcopy
from pathlib import Path
import yaml


def merge(base, extra):
    if isinstance(base, dict) and isinstance(extra, dict):
        result = deepcopy(base)
        for key, value in extra.items():
            result[key] = merge(result[key], value) if key in result else deepcopy(value)
        return result
    if isinstance(base, list) and isinstance(extra, list):
        return deepcopy(base + [value for value in extra if value not in base])
    return deepcopy(extra)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    base = yaml.safe_load((root / 'compose.yaml').read_text(encoding='utf-8'))
    overlay = yaml.safe_load((root / 'compose.intelligence.yaml').read_text(encoding='utf-8'))
    rendered = '# Generated by server/scripts/render_compose.py; edit the base/overlay and regenerate.\n' + yaml.safe_dump(merge(base, overlay), sort_keys=False, allow_unicode=True, width=120)
    target = root / 'compose.dokploy.yaml'
    if args.check:
        if target.read_text(encoding='utf-8') != rendered:
            raise SystemExit('compose.dokploy.yaml is stale; regenerate before deploying')
    else:
        target.write_text(rendered, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
